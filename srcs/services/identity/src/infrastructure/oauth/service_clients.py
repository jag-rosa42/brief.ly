"""The service client registry (ADR-0008): who may get which service token.

Each entry says, for one client (a backend service), which audiences it may
ask a token for, and which scopes for each audience. Identity refuses
everything else with INVALID_SCOPE.

There is no secret here. Each client's secret is one Compose secret,
`<client_id with _>_client_secret` (e.g. `ai_processing_client_secret`),
generated by `make secrets` and mounted into Identity and into that client.

To add a client:
1. add it below, with the least scopes it needs;
2. add its secret to `CLIENT_SECRET_FILES` in shared/mk/secrets.mk;
3. in compose.yaml, declare the secret and mount it into identity and into
   the client's service.

The scopes are the ones of docs/api/04_content-management.md.
"""

from collections.abc import Mapping

from src.domain.entities.service_client import ServiceClient

CONTENT_MANAGEMENT_AUDIENCE: str = "transcendence:content-management"

SERVICE_CLIENTS: tuple[ServiceClient, ...] = (
    ServiceClient(
        client_id="personalization",
        allowed_scopes={
            CONTENT_MANAGEMENT_AUDIENCE: frozenset({
                "topics:read",
                "articles:read"
            }),
        },
    ),
    ServiceClient(
        client_id="morning-briefing",
        allowed_scopes={
            CONTENT_MANAGEMENT_AUDIENCE: frozenset({
                "topics:read",
                "articles:read"
            }),
        },
    ),
    ServiceClient(
        client_id="ai-processing",
        allowed_scopes={
            CONTENT_MANAGEMENT_AUDIENCE: frozenset({
                "topics:read",
                "articles:read",
                "summaries:write"
            }),
        },
    ),
)


class InMemoryServiceClientRegistry:
    """The ServiceClientRegistry adapter: looks clients up in SERVICE_CLIENTS."""

    def __init__(
        self,
        clients: tuple[ServiceClient, ...] = SERVICE_CLIENTS,
    ) -> None:
        self._clients: Mapping[str, ServiceClient] = {
            client.client_id: client for client in clients
        }

    def find(self, client_id: str) -> ServiceClient | None:
        return self._clients.get(client_id)

    def client_ids(self) -> frozenset[str]:
        return frozenset(self._clients)
